// Boosters added on 2026-11-15 to bring the tree towards the design target (section 5 of
// docs/design.md: about 25 boosters per branch). Each one hangs after the last upgrade of its big
// node, so a saved profile keeps every node it had, and gets an id after the 995 nodes saved
// profiles know (preview.rs numbers them last).
//
// Rules the list follows:
// - Every effect key is one the game already applies and that was checked in game.
// - A deeper step of the big node's own key is smaller than the step before it.
// - A big node whose own effect is capped or a switch gets a key of the branch's small nodes
//   (or a neighbouring branch's) at about two small nodes' worth. Never another big node's
//   switch: that would hand out the other big node's effect.
// - Nothing makes the branch's own experience come faster (no extra fish, twins, faster
//   furnaces or stands), so the pace of section 14 holds.

